#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
rmsf_convergence.py
===================

RMSF convergence analysis (WT and mutant systems).
5 residues are trimmed from each terminus of every chain before statistics.

Files read (generated by run_rmsf_block.sh):
    Regular (unwrapping segments excluded):
        <system>/<run>/rmsf-<histone>_chain_<chain>.dat              (100-500 ns)
        <system>/<run>/rmsf-<histone>_chain_<chain>_100to300ns.dat
        <system>/<run>/rmsf-<histone>_chain_<chain>_300to500ns.dat
    No-exclusion (only present for K74N run1/run3, F70L run3):
        same names + _noexcl

Two sets are produced in one run:
    Set A "excluded": all systems, outputs conv_half.csv / conv_replica.csv / conv_summary.csv
    Set B "no-exclusion": only runs that have _noexcl files (other systems are skipped,
                          no duplicate computation), outputs conv_*_noexcl.csv
    WT in Set B uses only the same run set as those systems, ensuring both sets
    have the same sample size and are comparable.

Computed quantities:
  1. Half-trajectory convergence (per replica, per chain):
       100-300 ns vs 300-500 ns RMSF -> PCC / RMSD / mean shift
  2. Replicate consistency (per system, per chain):
       pairwise comparison of 100-500 ns runs -> PCC / RMSD / mean shift
"""

from pathlib import Path
from itertools import combinations

import numpy as np
import pandas as pd
from scipy import stats


# ========== Configuration ==========
BASE_DIR = Path(__file__).resolve().parent

RUNS = ["run1", "run2", "run3"]
WT_SYSTEM = "WT_rw"
NOEXCL = "_noexcl"

# Two variants
VARIANTS = [
    {"suffix": "",        "label": "excluded segments"},
    {"suffix": NOEXCL,    "label": "no excluded segments"},
]

TRIM_N_TERM = 5
TRIM_C_TERM = 5

MUTATION_MAP = {
    "R29Q":  {"histone": "H2A"},
    "E56K":  {"histone": "H2A"},
    "K74N":  {"histone": "H2A"},
    "F70L":  {"histone": "H2B"},
    "E50K":  {"histone": "H3"},
    "E73K":  {"histone": "H3"},
    "E105K": {"histone": "H3"},
}

HISTONE_CHAIN_PAIRS = {
    "H3":  ("A", "B"),
    "H2A": ("C", "D"),
    "H2B": ("C", "D"),
}

CHAIN_TO_HISTONE = {
    "A": "H3", "B": "H4", "C": "H2A", "D": "H2B",
    "E": "H3", "F": "H4", "G": "H2A", "H": "H2B",
}

# Columns for empty DataFrames to avoid KeyError
HALF_COLS = ["system", "chain", "histone", "run", "trim", "n_residues",
             "PCC_100_300_vs_300_500", "RMSD_100_300_vs_300_500",
             "mean_100_300", "mean_300_500", "delta_mean"]
REP_COLS  = ["system", "chain", "histone", "pair", "trim", "n_residues",
             "PCC", "RMSD", "mean_run1", "mean_run2", "delta_mean"]
SUM_COLS  = ["system", "chain", "histone", "trim", "n_runs_half",
             "mean_PCC_half", "min_PCC_half", "mean_RMSD_half", "mean_abs_delta_half",
             "n_pairs_replica", "mean_PCC_replica", "min_PCC_replica",
             "mean_RMSD_replica", "mean_RMSF_100_500"]


# ========== Helpers ==========
def read_rmsf(path: Path,
              trim_n: int = TRIM_N_TERM,
              trim_c: int = TRIM_C_TERM) -> pd.DataFrame:
    df = pd.read_csv(path, comment="#", sep=r"\s+", header=None,
                     names=["Res", "RMSF"])
    df["Res"] = df["Res"].round().astype(int)
    df = df.sort_values("Res").reset_index(drop=True)

    n = len(df)
    if (trim_n > 0 or trim_c > 0) and n > (trim_n + trim_c):
        df = df.iloc[trim_n: n - trim_c].reset_index(drop=True)
    return df


def align2(df1: pd.DataFrame, df2: pd.DataFrame):
    m = pd.merge(df1, df2, on="Res", suffixes=("_1", "_2"), how="inner")
    return m["Res"].to_numpy(), m["RMSF_1"].to_numpy(), m["RMSF_2"].to_numpy()


def pcc(x, y) -> float:
    if len(x) < 3 or np.std(x) == 0 or np.std(y) == 0:
        return np.nan
    return float(stats.pearsonr(x, y)[0])


def rmsd(x, y) -> float:
    return float(np.sqrt(np.mean((x - y) ** 2)))


def chains_for_system(system: str):
    if system == WT_SYSTEM:
        chains = set()
        for info in MUTATION_MAP.values():
            chains.update(HISTONE_CHAIN_PAIRS[info["histone"]])
        return sorted(chains)
    mut = system.replace("_rw", "")
    if mut in MUTATION_MAP:
        return list(HISTONE_CHAIN_PAIRS[MUTATION_MAP[mut]["histone"]])
    return []


def runs_with_noexcl(system: str) -> list:
    """Return runs that have _noexcl files (probe with H3 chain A)."""
    out = []
    for run in RUNS:
        if (BASE_DIR / system / run / f"rmsf-H3_chain_A{NOEXCL}.dat").exists():
            out.append(run)
    return out


def scan_noexcl():
    """Scan all mutant systems, return {system: [runs]} and the union of runs needed for WT."""
    m = {}
    for mut in MUTATION_MAP:
        sys_name = f"{mut}_rw"
        r = runs_with_noexcl(sys_name)
        if r:
            m[sys_name] = r
    wt_runs = sorted({r for rs in m.values() for r in rs})
    return m, wt_runs


# ========== Single-variant analysis ==========
def run_variant(suffix: str, exclude_runs: dict, wt_use_runs: list, label: str):
    """
    suffix        : "" or "_noexcl", used to build filenames
    exclude_runs  : {system: [runs to skip]}; Set A uses an empty dict
    wt_use_runs   : WT uses only these runs (Set A uses all RUNS)
    """
    half_rows, rep_rows = [], []
    systems = [WT_SYSTEM] + [f"{m}_rw" for m in MUTATION_MAP]
    trim_label = f"N{TRIM_N_TERM}_C{TRIM_C_TERM}" if (TRIM_N_TERM or TRIM_C_TERM) else "none"

    print(f"\n{'#'*68}")
    print(f"#  VARIANT: {label}   (filename suffix = '{suffix or 'none'}')")
    print(f"#  WT runs used: {wt_use_runs}")
    if exclude_runs:
        print(f"#  runs skipped: {exclude_runs}")
    print(f"{'#'*68}")

    for system in systems:
        sys_dir = BASE_DIR / system
        if not sys_dir.exists():
            print(f"[WARN] Missing system dir: {sys_dir}")
            continue

        skip = set(exclude_runs.get(system, []))
        use_runs = [r for r in (wt_use_runs if system == WT_SYSTEM else RUNS) if r not in skip]
        if not use_runs:
            print(f"[SKIP] {system}: no run left after skipping {sorted(skip)}")
            continue

        # Warn if fewer than 2 runs -> cannot do pairwise replica comparison
        if len(use_runs) < 2:
            print(f"[WARN] {system}: only {len(use_runs)} usable run(s) "
                  f"{use_runs} -> no replicate pair, "
                  f"replica-consistency part will be empty")

        for chain in chains_for_system(system):
            file_histone = CHAIN_TO_HISTONE[chain]

            # ---- (1) Half-trajectory convergence (per run) ----
            for run in use_runs:
                f1 = sys_dir / run / f"rmsf-{file_histone}_chain_{chain}_100to300ns{suffix}.dat"
                f2 = sys_dir / run / f"rmsf-{file_histone}_chain_{chain}_300to500ns{suffix}.dat"
                if not (f1.exists() and f2.exists()):
                    print(f"[MISS] {system}/{run}: {f1.name} / {f2.name}")
                    continue

                res, y1, y2 = align2(read_rmsf(f1), read_rmsf(f2))
                if len(res) == 0:
                    continue

                half_rows.append({
                    "system":  system,
                    "chain":   chain,
                    "histone": file_histone,
                    "run":     run,
                    "trim":    trim_label,
                    "n_residues": len(res),
                    "PCC_100_300_vs_300_500":  pcc(y1, y2),
                    "RMSD_100_300_vs_300_500": rmsd(y1, y2),
                    "mean_100_300": float(np.mean(y1)),
                    "mean_300_500": float(np.mean(y2)),
                    "delta_mean":   float(np.mean(y2) - np.mean(y1)),
                })

            # ---- (2) Replicate consistency (100-500 ns) ----
            full = {}
            for run in use_runs:
                f = sys_dir / run / f"rmsf-{file_histone}_chain_{chain}{suffix}.dat"
                if not f.exists():
                    print(f"[MISS] {f}")
                    continue
                full[run] = read_rmsf(f)

            for r1, r2 in combinations(use_runs, 2):
                if r1 not in full or r2 not in full:
                    continue
                res, y1, y2 = align2(full[r1], full[r2])
                if len(res) == 0:
                    continue

                rep_rows.append({
                    "system":  system,
                    "chain":   chain,
                    "histone": file_histone,
                    "pair":    f"{r1}_vs_{r2}",
                    "trim":    trim_label,
                    "n_residues": len(res),
                    "PCC":  pcc(y1, y2),
                    "RMSD": rmsd(y1, y2),
                    "mean_run1": float(np.mean(y1)),
                    "mean_run2": float(np.mean(y2)),
                    "delta_mean": float(np.mean(y2) - np.mean(y1)),
                })

    # ---- Write per-row CSVs (keep columns even if empty) ----
    df_half = pd.DataFrame(half_rows, columns=HALF_COLS)
    df_rep  = pd.DataFrame(rep_rows,  columns=REP_COLS)

    half_csv = BASE_DIR / f"conv_half{suffix}.csv"
    rep_csv  = BASE_DIR / f"conv_replica{suffix}.csv"
    sum_csv  = BASE_DIR / f"conv_summary{suffix}.csv"

    df_half.to_csv(half_csv, index=False, float_format="%.4f")
    df_rep .to_csv(rep_csv,  index=False, float_format="%.4f")

    # ---- Summary per (system, chain) ----
    summary_rows = []
    keys = sorted(set([(r["system"], r["chain"]) for r in half_rows] +
                      [(r["system"], r["chain"]) for r in rep_rows]))
    for system, chain in keys:
        g_half = df_half[(df_half["system"] == system) & (df_half["chain"] == chain)]
        g_rep  = df_rep [(df_rep ["system"] == system) & (df_rep ["chain"] == chain)]
        histone = (g_half["histone"].iloc[0] if len(g_half)
                   else g_rep["histone"].iloc[0])

        mean_rmsf = np.nan
        if len(g_half):
            mean_rmsf = 0.5 * (g_half["mean_100_300"].mean()
                               + g_half["mean_300_500"].mean())

        summary_rows.append({
            "system":  system,
            "chain":   chain,
            "histone": histone,
            "trim":    trim_label,
            "n_runs_half":         len(g_half),
            "mean_PCC_half":       g_half["PCC_100_300_vs_300_500"].mean() if len(g_half) else np.nan,
            "min_PCC_half":        g_half["PCC_100_300_vs_300_500"].min()  if len(g_half) else np.nan,
            "mean_RMSD_half":      g_half["RMSD_100_300_vs_300_500"].mean() if len(g_half) else np.nan,
            "mean_abs_delta_half": g_half["delta_mean"].abs().mean()        if len(g_half) else np.nan,
            "n_pairs_replica":     len(g_rep),
            "mean_PCC_replica":    g_rep["PCC"].mean()  if len(g_rep) else np.nan,
            "min_PCC_replica":     g_rep["PCC"].min()   if len(g_rep) else np.nan,
            "mean_RMSD_replica":   g_rep["RMSD"].mean() if len(g_rep) else np.nan,
            "mean_RMSF_100_500":   mean_rmsf,
        })

    df_sum = pd.DataFrame(summary_rows, columns=SUM_COLS)
    df_sum.to_csv(sum_csv, index=False, float_format="%.4f")

    print(f"\n[OK] {half_csv.name}     rows = {len(df_half)}")
    print(f"[OK] {rep_csv.name}      rows = {len(df_rep)}")
    print(f"[OK] {sum_csv.name}      rows = {len(df_sum)}")

    if len(df_sum):
        print(f"\n=========== Summary [{label}] ===========")
        cols = ["system", "chain", "histone",
                "mean_PCC_half", "mean_RMSD_half",
                "mean_PCC_replica", "mean_RMSD_replica",
                "mean_RMSF_100_500"]
        print(df_sum[cols].to_string(index=False, float_format="%.3f"))

    return df_sum


# ========== Main ==========
def main():
    noexcl_map, wt_runs = scan_noexcl()

    print("=" * 68)
    print("[Set B scan] Which runs have _noexcl files (only these systems go to Set B)")
    if noexcl_map:
        for sys_name, rs in noexcl_map.items():
            print(f"  {sys_name:12s} -> {rs}")
        print(f"  WT runs used in Set B = {wt_runs}")
    else:
        print("  No _noexcl files found, Set B will be empty")
    print("=" * 68)

    # ---- Set A: excluded (all runs) ----
    sum_a = run_variant(suffix="", exclude_runs={}, wt_use_runs=list(RUNS),
                        label="excluded segments")

    # ---- Set B: no-exclusion (only systems with _noexcl; WT uses the same run set) ----
    if noexcl_map:
        # Skip runs that do not have _noexcl in that system; WT uses only wt_runs
        skip_map = {sys_name: [r for r in RUNS if r not in rs]
                    for sys_name, rs in noexcl_map.items()}
        sum_b = run_variant(suffix=NOEXCL, exclude_runs=skip_map,
                            wt_use_runs=wt_runs, label="no excluded segments")
    else:
        sum_b = pd.DataFrame(columns=SUM_COLS)

    # ---- Comparison of the two sets (only systems that have both variants) ----
    if len(sum_a) and len(sum_b):
        print("\n" + "=" * 88)
        print("[Comparison] excluded vs no-exclusion (only systems with _noexcl)")
        print("=" * 88)
        changed = sorted(noexcl_map.keys())
        cols = ["system", "chain", "mean_PCC_half", "mean_PCC_replica",
                "mean_RMSD_replica", "mean_RMSF_100_500"]
        a = sum_a[sum_a["system"].isin(changed)][cols].copy()
        b = sum_b[sum_b["system"].isin(changed)][cols].copy()
        merged = a.merge(b, on=["system", "chain"], suffixes=("_excl", "_noexcl"))
        pd.set_option("display.width", 160)
        print(merged.to_string(index=False, float_format="%.3f"))
        merged.to_csv(BASE_DIR / "conv_compare_excl_vs_noexcl.csv",
                      index=False, float_format="%.4f")
        print("\n[OK] conv_compare_excl_vs_noexcl.csv")

        # Range summary for direct use in table footnotes
        for name, d in [("Set A excluded", sum_a), ("Set B no-exclusion", sum_b)]:
            w = d[d["system"] == WT_SYSTEM]
            m = d[d["system"] != WT_SYSTEM]
            # Protect against empty subsets
            def _rng(series):
                s = series.dropna()
                return (f"{s.min():.2f}-{s.max():.2f}") if len(s) else "N/A"
            def _rng3(series):
                s = series.dropna()
                return (f"{s.min():.3f}-{s.max():.3f} Å") if len(s) else "N/A"

            print(f"\n[{name}] WT   mean PCC (half) = "
                  f"{_rng(w['mean_PCC_half'])} ; "
                  f"mean PCC (replica) = "
                  f"{_rng(w['mean_PCC_replica'])}")
            print(f"[{name}] mut  mean PCC (half) = "
                  f"{_rng(m['mean_PCC_half'])} ; "
                  f"mean PCC (replica) = "
                  f"{_rng(m['mean_PCC_replica'])} ; "
                  f"mean RMSD (replica) = "
                  f"{_rng3(m['mean_RMSD_replica'])}")


if __name__ == "__main__":
    main()